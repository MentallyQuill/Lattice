import assert from 'node:assert/strict';
import {createApplicationFileExperience} from '../src/ui/application-file-experience.js';
import {createWorkflowDocumentSession} from '../src/ui/document-session.js';
import {memoryStore,graph} from './workflow-saved-library.test.mjs';
const store=memoryStore(),session=createWorkflowDocumentSession();session.activate(graph());
let user='alice',context='chat-a',mode,downloaded=false;
const server={serviceVersion:null,refresh:async()=>({ok:false,error:{code:'FILE_SERVICE_REQUIRED',message:'Optional component absent'}})};
const app=createApplicationFileExperience({store,server,session,getUserId:()=>user,getHost:()=>({hostId:'host',userId:user}),getContext:()=>context,showWelcome:true,configureStorageMode:callback=>mode=callback,downloadSetup:()=>{downloaded=true;}});
await app.setup.ready;
assert.equal(app.setup.view().open,true,'fresh authenticated user sees two storage choices');
assert.equal(mode(),'inside');
await app.setup.choose('inside');assert.equal(app.setup.view().open,false);
assert.equal((await app.controller.save()).ok,true);
const shared=app.controller.getWorkflowIdentity();assert.notEqual(shared,'original');
session.current().nodes.text.text='saved edit';app.controller.changed();
assert.equal((await app.controller.beforeRun()).ok,true);
assert.equal(app.controller.view().autosave.label,'Saved in SillyTavern');
const copy=await app.controller.saveAs('Another chat');assert.equal(copy.ok,true);assert.notEqual(app.controller.getWorkflowIdentity(),shared);
await app.setup.choose('anywhere');assert.equal(mode(),'inside','missing optional support cannot disable automatic saving');
await app.setup.download();assert.equal(downloaded,true);await app.setup.cancel();
app.controller.dispose();app.setup.dispose();
const reopened=createApplicationFileExperience({store,server,session,getUserId:()=>user,getHost:()=>({hostId:'host',userId:user}),getContext:()=>context,showWelcome:true});
await reopened.setup.ready;assert.equal(reopened.setup.view().open,false,'restart remembers storage choice');
reopened.controller.dispose();reopened.setup.dispose();
console.log('application file experience: setup, host saving, independent copies and restart passed');
